function C = spread_stage_configs(stage)
% Configurations for each search stage. Stage B changes one setting at a
% time from the Stage A baseline.
    base = {'name', 'A0_baseline', 'base', 'OIS', 'pc', 'pca_est', 'big4', 'Dec-21', 'fiscal', 'ff_nom', ...
            'window', {'Mar2009', 'Dec2021'}, 'w', 0.5, 'gamma', 'fiscal_only', 'signConstraint', true};
    switch stage
        case 'A'
            C = {spread_config(base{:})};
        case 'B'
            v = { {'name', 'B01_baseDE',        'base', 'DE'}, ...
                  {'name', 'B02_observableLS',  'pc', 'observable'}, ...
                  {'name', 'B03_fiscal_ffgdp',  'fiscal', 'ffgdp'}, ...
                  {'name', 'B04_fiscal_sim2015','fiscal', 'ff_nom_sim2015'}, ...
                  {'name', 'B05_win_Dec09Aug14','window', {'Dec2009', 'Aug2014'}}, ...
                  {'name', 'B06_win_Mar09Feb20','window', {'Mar2009', 'Feb2020'}}, ...
                  {'name', 'B07_win_Jan12Dec21','window', {'Jan2012', 'Dec2021'}}, ...
                  {'name', 'B08_w025',          'w', 0.25}, ...
                  {'name', 'B09_w010',          'w', 0.10}, ...
                  {'name', 'B10_gamma_all',     'gamma', 'all'} };
            C = cell(size(v));
            for k = 1:numel(v), C{k} = spread_config(base{:}, v{k}{:}); end
        case 'C'
            % Start from the replication of Estimates_spread_DEIT_PEPP.m (best Stage-B-type fit)
            % with all constraints on, then change one setting at a time; plus long-window combinations.
            repl = {'base', 'DE', 'pc', 'pca_est', 'big4', 'Mar-15', 'fiscal', 'ff_nom', 'window', {'Dec2009', 'Aug2014'}, ...
                    'w', 0.5, 'gamma', 'all', 'signConstraint', true};
            longw = {'base', 'DE', 'pc', 'pca_est', 'big4', 'Dec-21', 'fiscal', 'ff_nom', 'window', {'Mar2009', 'Dec2021'}, ...
                     'w', 0.10, 'gamma', 'all', 'signConstraint', true};
            v = { [repl {'name', 'C01_repl_constrained'}], ...
                  [repl {'name', 'C02_repl_big4Dec21', 'big4', 'Dec-21'}], ...
                  [repl {'name', 'C03_repl_fiscalonly', 'gamma', 'fiscal_only'}], ...
                  [repl {'name', 'C04_repl_w010', 'w', 0.10}], ...
                  [repl {'name', 'C05_repl_OIS', 'base', 'OIS'}], ...
                  [repl {'name', 'C06_repl_ffgdp', 'fiscal', 'ffgdp'}], ...
                  [repl {'name', 'C07_repl_cap10pa', 'maxIntensity', 0.10}], ...
                  [repl {'name', 'C08_repl_w025', 'w', 0.25}], ...
                  [repl {'name', 'C09_repl_observable', 'pc', 'observable'}], ...
                  [longw {'name', 'C10_long_DE_ffnom'}], ...
                  [longw {'name', 'C11_long_DE_ffgdp', 'fiscal', 'ffgdp'}], ...
                  [longw {'name', 'C12_long_OIS_ffnom', 'base', 'OIS'}] };
            C = cell(size(v));
            for k = 1:numel(v), C{k} = spread_config(v{k}{:}); end
        case 'D'
            % Refine the best long-window candidate (C11: DE base, net debt/GDP, 2009-2021):
            % weights, fiscal-only default intensity, random restarts; plus a restart of C04.
            c11 = {'base', 'DE', 'pc', 'pca_est', 'big4', 'Dec-21', 'fiscal', 'ffgdp', 'window', {'Mar2009', 'Dec2021'}, ...
                   'w', 0.10, 'gamma', 'all', 'signConstraint', true, 'maxIter', 1500, 'penalty', 1e3};
            x11 = load_x('C11_long_DE_ffgdp'); x04 = load_x('C04_repl_w010');
            c04 = {'base', 'DE', 'pc', 'pca_est', 'big4', 'Mar-15', 'fiscal', 'ff_nom', 'window', {'Dec2009', 'Aug2014'}, ...
                   'w', 0.10, 'gamma', 'all', 'signConstraint', true, 'maxIter', 1500, 'penalty', 1e3};
            v = { [c11 {'name', 'D01_C11_w010_long', 'x0', x11}], ...
                  [c11 {'name', 'D02_C11_w020', 'w', 0.20, 'x0', x11}], ...
                  [c11 {'name', 'D03_C11_w030', 'w', 0.30, 'x0', x11}], ...
                  [c11 {'name', 'D04_C11_fiscalonly', 'gamma', 'fiscal_only'}], ...
                  [c11 {'name', 'D05_C11_restart1', 'x0', jitter(x11, 1)}], ...
                  [c11 {'name', 'D06_C11_restart2', 'x0', jitter(x11, 2)}], ...
                  [c11 {'name', 'D07_C11_restart3', 'x0', jitter(x11, 3)}], ...
                  [c04 {'name', 'D08_C04_restart1', 'x0', jitter(x04, 4)}] };
            C = cell(size(v));
            for k = 1:numel(v), C{k} = spread_config(v{k}{:}); end
        case 'E'
            % Estimated through Dec 2021, with Gamma_1 on the fiscal factor >= 0 and the
            % IT default intensity capped (10% p.a. unless stated).
            e = {'base', 'DE', 'pc', 'pca_est', 'big4', 'Dec-21', 'fiscal', 'ffgdp', 'window', {'Mar2009', 'Dec2021'}, ...
                 'w', 0.10, 'gamma', 'all', 'fiscalGammaNonneg', true, 'maxIntensity', 0.10, 'signConstraint', true, ...
                 'maxIter', 1500, 'penalty', 1e3};
            x06 = load_x('D06_C11_restart2');
            v = { [e {'name', 'E01_ffgdp_fromD06', 'x0', x06}], ...
                  [e {'name', 'E02_ffgdp_fresh'}], ...
                  [e {'name', 'E03_ffgdp_w020', 'w', 0.20, 'x0', x06}], ...
                  [e {'name', 'E04_ffnom', 'fiscal', 'ff_nom'}], ...
                  [e {'name', 'E05_ffgdp_cap20', 'maxIntensity', 0.20, 'x0', x06}], ...
                  [e {'name', 'E06_ffgdp_restart', 'x0', jitter(x06, 5)}], ...
                  [e {'name', 'E07_ffgdp_OIS', 'base', 'OIS'}], ...
                  [e {'name', 'E08_ffgdp_fiscalonly', 'gamma', 'fiscal_only'}] };
            C = cell(size(v));
            for k = 1:numel(v), C{k} = spread_config(v{k}{:}); end
        case 'F'
            % As Stage E (estimated through Dec 2021, Gamma_1 on fiscal >= 0, intensity <= 10% p.a.),
            % but fitting DE and the IT-DE spread instead of DE and IT.
            f = {'base', 'DE', 'pc', 'pca_est', 'big4', 'Dec-21', 'fiscal', 'ffgdp', 'window', {'Mar2009', 'Dec2021'}, ...
                 'w', 0.10, 'gamma', 'all', 'fiscalGammaNonneg', true, 'maxIntensity', 0.10, 'signConstraint', true, ...
                 'maxIter', 1500, 'penalty', 1e3, 'target', 'spread'};
            x06 = load_x('E06_ffgdp_restart'); x08 = load_x('E08_ffgdp_fiscalonly');
            v = { [f {'name', 'F01_E06_spread', 'x0', x06}], ...
                  [f {'name', 'F02_E06_spread_fresh'}], ...
                  [f {'name', 'F03_E08_spread', 'gamma', 'fiscal_only', 'x0', x08}], ...
                  [f {'name', 'F05_E06_spread_weight2', 'spreadWeight', 2, 'x0', x06}], ...
                  [f {'name', 'F06_E06_spread_w005', 'w', 0.05, 'x0', x06}], ...
                  [f {'name', 'F07_E06_spread_restart', 'x0', jitter(x06, 6)}], ...
                  [f {'name', 'F08_E07_OIS_spread', 'base', 'OIS', 'x0', load_x('E07_ffgdp_OIS')}] };
            C = cell(size(v));
            for k = 1:numel(v), C{k} = spread_config(v{k}{:}); end
        case 'G'
            % As Stage F (DE and IT-DE spread, estimated through Dec 2021, restrictions on), but the
            % event part of the fit uses only the PEPP reaction; APP is reported out of sample.
            g = {'base', 'DE', 'pc', 'pca_est', 'big4', 'Dec-21', 'fiscal', 'ffgdp', 'window', {'Mar2009', 'Dec2021'}, ...
                 'w', 0.05, 'gamma', 'all', 'fiscalGammaNonneg', true, 'maxIntensity', 0.10, 'signConstraint', true, ...
                 'maxIter', 1500, 'penalty', 1e3, 'target', 'spread', 'events', {'PEPP'}};
            xF06 = load_x('F06_E06_spread_w005'); xF02 = load_x('F02_E06_spread_fresh');
            v = { [g {'name', 'G01_PEPP_w005', 'x0', xF06}], ...
                  [g {'name', 'G02_PEPP_w010', 'w', 0.10, 'x0', xF02}], ...
                  [g {'name', 'G03_PEPP_w005_fresh'}], ...
                  [g {'name', 'G04_PEPP_w002', 'w', 0.02, 'x0', xF06}], ...
                  [g {'name', 'G05_PEPP_fiscalonly', 'gamma', 'fiscal_only', 'x0', load_x('F03_E08_spread')}], ...
                  [g {'name', 'G06_PEPP_restart', 'x0', jitter(xF06, 7)}], ...
                  [g {'name', 'G07_PEPP_OIS', 'base', 'OIS', 'x0', load_x('F08_E07_OIS_spread')}], ...
                  [g {'name', 'G08_PEPP_ffnom', 'fiscal', 'ff_nom'}] };
            C = cell(size(v));
            for k = 1:numel(v), C{k} = spread_config(v{k}{:}); end
        case 'H'
            % G01 setup (DE and IT-DE spread, estimated through Dec 2021, restrictions on, w = 0.05),
            % but fitted to the APP reaction only; PEPP is reported out of sample.
            h = {'base', 'DE', 'pc', 'pca_est', 'big4', 'Dec-21', 'fiscal', 'ffgdp', 'window', {'Mar2009', 'Dec2021'}, ...
                 'w', 0.05, 'gamma', 'all', 'fiscalGammaNonneg', true, 'maxIntensity', 0.10, 'signConstraint', true, ...
                 'maxIter', 1500, 'penalty', 1e3, 'target', 'spread', 'events', {'APP'}};
            xG01 = load_x('G01_PEPP_w005'); xF06 = load_x('F06_E06_spread_w005');
            v = { [h {'name', 'H01_APP_fromG01', 'x0', xG01}], ...
                  [h {'name', 'H02_APP_fromF06', 'x0', xF06}], ...
                  [h {'name', 'H03_APP_fresh'}], ...
                  [h {'name', 'H04_APP_w002', 'w', 0.02, 'x0', xF06}], ...
                  [h {'name', 'H05_APP_w010', 'w', 0.10, 'x0', xF06}], ...
                  [h {'name', 'H06_APP_restart', 'x0', jitter(xF06, 8)}] };
            C = cell(size(v));
            for k = 1:numel(v), C{k} = spread_config(v{k}{:}); end
        case 'I'
            % G (PEPP only) and H (APP only) setups with w = 0: no weight on the yield fit.
            b = {'base', 'DE', 'pc', 'pca_est', 'big4', 'Dec-21', 'fiscal', 'ffgdp', 'window', {'Mar2009', 'Dec2021'}, ...
                 'w', 0, 'gamma', 'all', 'fiscalGammaNonneg', true, 'maxIntensity', 0.10, 'signConstraint', true, ...
                 'maxIter', 1500, 'penalty', 1e3, 'target', 'spread'};
            xG01 = load_x('G01_PEPP_w005'); xF06 = load_x('F06_E06_spread_w005');
            v = { [b {'name', 'I01_PEPP_w0_fromG01', 'events', {'PEPP'}, 'x0', xG01}], ...
                  [b {'name', 'I02_APP_w0_fromG01',  'events', {'APP'},  'x0', xG01}], ...
                  [b {'name', 'I03_PEPP_w0_fromF06', 'events', {'PEPP'}, 'x0', xF06}], ...
                  [b {'name', 'I04_APP_w0_fromF06',  'events', {'APP'},  'x0', xF06}] };
            C = cell(size(v));
            for k = 1:numel(v), C{k} = spread_config(v{k}{:}); end
        otherwise
            error('spread_stage_configs: unknown stage %s', stage);
    end
end

function x = load_x(name)
% Warm start from an earlier run; empty (default starting values) if that run is not available.
    f = fullfile('Output_runs', [name '.mat']);
    if exist(f, 'file'), s = load(f); x = s.R.x; else x = []; end
end

function x = jitter(x, seed)
% Random restart: perturb every parameter by 50% of its size (at least 0.2), keep Gamma >= 0 where needed.
    if isempty(x), return; end
    rng(seed);
    x = x + max(0.5 * abs(x), 0.2) .* randn(size(x));
end
